#!/usr/bin/env python3
"""Build zrn-snapshot-list.h: every register the ztOS sleep tables and the
Samsung lpm_init subset touch (sleep-tables.h, init-memory.h), plus the PMU
wake/idle/hint words and the alive-GPIO EINT words. These are registers the
sleep path already reads or writes, so reading them is safe. Conditional
entries (COND_*) keep their condition: a clock register of a powered-off
domain faults, so it is read only when its domain-status condition holds,
the same rule the sequence engine follows.

    gen-snapshot-list.py ../sleep-tables.h ../init-memory.h > zrn-snapshot-list.h
"""
import re
import sys

seq = re.compile(r'ZRN_SEQ\(\s*(\w+),\s*"([^"]*)",\s*(0x[0-9a-fA-F]+|0),\s*(0x[0-9a-fA-F]+|0),'
                 r'[^,]+,[^,]+,\s*(0x[0-9a-fA-F]+|0),\s*(0x[0-9a-fA-F]+|0),\s*([^,]+),\s*([^)]+\)?[^)]*)\)')
init = re.compile(r'\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*0x[0-9a-fA-F]+,\s*0x[0-9a-fA-F]+,\s*"([^"]+)"')

regs = {}   # addr -> (name, cond) ; cond None = unconditional


def add(addr, name, cond):
    old = regs.get(addr)
    if old is None or (old[1] is not None and cond is None):
        regs[addr] = (name, cond)


def seq_args(line):
    """Split one ZRN_SEQ(...) line into its 10 arguments, respecting parentheses."""
    s = line[line.index('ZRN_SEQ(') + 8:line.rindex(')')]
    out, depth, cur = [], 0, ''
    for ch in s:
        depth += ch == '('
        depth -= ch == ')'
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    out.append(cur.strip())
    return out


src = open(sys.argv[1]).read()
for line in src.splitlines():
    if 'ZRN_SEQ(PMUCAL' not in line:
        continue
    op, name, b, o, _m, _v, cb, co, cm, cv = seq_args(line)
    name = name.strip('"')
    b, o = int(b, 16), int(o, 16)
    if b == 0:
        continue
    cond = None
    if op.startswith('PMUCAL_COND') and int(cb, 16):
        cond = (int(cb, 16) + int(co, 16), cm.strip(), cv.strip())
        add(cond[0], name + '_cond', None)
    add(b + o, name, cond)
for m in init.finditer(open(sys.argv[2]).read()):
    add(int(m.group(1), 16) + int(m.group(2), 16), m.group(3), None)

PMU, GPIO, INTR = 0x14060000, 0x14050000, 0x14070000
# only the wake words the sleep path writes: 0x620-0x640 hold registers that
# fault on read (0x14060634 aborted on 2026-11-08), like INFORM 0x818
for o in list(range(0x3f0, 0x400, 4)) + list(range(0x600, 0x620, 4)) + [0x644, 0x860]:
    add(PMU + o, 'PMU_WAKE_IDLE_%03x' % o, None)
for o in [0x20, 0x24, 0x28, 0x2c, 0x40, 0x44, 0x48, 0x4c, 0x60, 0x64, 0x68, 0x6c, 0x80, 0x84, 0x88, 0x8c]:
    add(GPIO + o, 'GPA_%03x' % o, None)
for o in list(range(0x700, 0x714, 4)) + list(range(0x800, 0x824, 4)) + list(range(0x900, 0x914, 4)) + list(range(0xa00, 0xa14, 4)):
    add(GPIO + o, 'EINT_%03x' % o, None)
for o in [0x100, 0x104, 0x108, 0x10c, 0x200, 0x204, 0x208, 0x20c, 0x400, 0x404, 0x408, 0x40c, 0x500, 0x504, 0x508, 0x50c]:
    add(INTR + o, 'INTR_GEN_%03x' % o, None)

# CPU cluster CMUs (0x1D0xxxxx, 0x1D1xxxxx) fault when that cluster is
# hot-unplugged (0x1D111300 aborted at load on 2026-11-08): leave them out
regs = {a: v for a, v in regs.items() if (a >> 20) not in (0x1d0, 0x1d1)}
print('/* Generated by gen-snapshot-list.py: do not edit. */')
print('static const struct zrn_snap_reg zrn_snap_regs[] = {')
for addr in sorted(regs):
    name, cond = regs[addr]
    if cond:
        print(f'\t{{ {addr:#010x}, {cond[0]:#010x}, {cond[1]}, {cond[2]}, "{name}" }},')
    else:
        print(f'\t{{ {addr:#010x}, 0, 0, 0, "{name}" }},')
print('};')
print(f'/* {len(regs)} registers */')
