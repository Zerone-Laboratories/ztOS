#!/usr/bin/env python3
"""Copy the exact vendor local power-domain tables, rejecting unsupported ops.

Emits pd-tables.h from the vendor flexpmu_cal_local_exynos9810.h: per-domain
<dom>_on / <dom>_save / <dom>_off / <dom>_status PMUCAL arrays, transcribed
verbatim into struct zrn_seq for the shared sequence.c engine. Only the op set
the engine implements is permitted; anything else aborts the build loudly.
"""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ('third_party/vendor-kernel/drivers/soc/samsung/cal-if/'
                 'exynos9810/flexpmu_cal_local_exynos9810.h')

# The multimedia / audio SoC domains SYS_SLEEP must power down. Order is the
# driver's domain-bit order: AUD is bit 0 (first validated at runtime).
DOMAINS = ['aud', 'dpu', 'dspm', 'dsps', 'g2d', 'mfc', 'iva',
           'isppre', 'isphq', 'isplp', 'dcf', 'dcpost', 'dcrd', 'vts', 'chub']
PHASES = ['on', 'save', 'off', 'status']

# Exactly the ops zrn_sequence_run() in sequence.c implements. PMUCAL_CHECK_SKIP
# is handled in the RESTORE phase (skip the next entry when its value matches).
# PMUCAL_WRITE_WAIT (write a field, poll STATUS at offset+4) is used by CHUB
# bring-up. Anything outside this set must fail the build rather than be
# silently miscompiled.
SUPPORTED = {'PMUCAL_READ', 'PMUCAL_WRITE', 'PMUCAL_COND_READ',
             'PMUCAL_COND_WRITE', 'PMUCAL_SAVE_RESTORE',
             'PMUCAL_COND_SAVE_RESTORE', 'PMUCAL_WAIT', 'PMUCAL_CHECK_SKIP',
             'PMUCAL_WRITE_WAIT'}


def table(text, name):
    matches = re.findall(r'struct pmucal_seq ' + name +
                         r'\[\] = \{(.*?)\n\};', text, re.S)
    if len(matches) != 1:
        raise ValueError(f'{name}: expected exactly one source table')
    body = matches[0]
    operations = re.findall(r'PMUCAL_SEQ_DESC\((\w+)', body)
    unsupported = set(operations) - SUPPORTED
    if not operations or unsupported:
        raise ValueError(f'{name}: missing or unsupported operations '
                         f'{sorted(unsupported)}')
    # The driver reads STATUS directly; keep the transcribed status tables for
    # a future is_enabled consumer without warning on them meanwhile.
    qualifier = '__maybe_unused ' if name.endswith('_status') else ''
    return ('static struct zrn_seq ' + qualifier + name + '[] = {' +
            body.replace('PMUCAL_SEQ_DESC(', 'ZRN_SEQ(') + '\n};')


def generate(source):
    text = source.read_text()
    output = ['/* SPDX-License-Identifier: GPL-2.0-only */',
              '/* Generated by generate-pd-tables.py from the vendor Exynos9810',
              ' * local power-domain PMUCAL. Do not edit by hand.',
              f' * Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()} */',
              '#ifndef ZRN_PD_TABLES_H',
              '#define ZRN_PD_TABLES_H',
              '#include "sequence.h"',
              '#define ZRN_SEQ(op, name, b, o, m, v, cb, co, cm, cv) \\\n'
              '    { op, name, b, o, m, v, cb, co, cm, cv, 0, false }']
    for dom in DOMAINS:
        for phase in PHASES:
            output.append(table(text, f'{dom}_{phase}'))
    output.append('#undef ZRN_SEQ')
    output.append('#endif /* ZRN_PD_TABLES_H */')
    return '\n\n'.join(output) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(SOURCE)
    target = Path(__file__).with_name('pd-tables.h')
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit('pd-tables.h differs from the vendor source')
    else:
        target.write_text(result)
        print(f'wrote {target}')
