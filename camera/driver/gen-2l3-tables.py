#!/usr/bin/env python3
"""gen-2l3-tables.py SETB.H > zrn-cam-2l3.h: Samsung's register tables for the rear camera.

SETB.H is fimc-is-cis-2l3-setB.h from the vendor kernel. Each row is register, value, width;
the burst and delay rows keep their meaning from sensor_cis_set_registers()."""
import re, sys
text = open(sys.argv[1], errors="ignore").read()
NAMES = {"Reset_TnP": "reset_tnp", "Global": "global", "2016x1512_30fps": "mode_2016x1512_30"}
print("/* SPDX-License-Identifier: GPL-2.0 */\n/* Generated by gen-2l3-tables.py from the vendor kernel's fimc-is-cis-2l3-setB.h */")
print("#define TB_BURST_ADDR 0xfffffffe\n#define TB_BURST_DATA 0xfffffffd\n#define TB_DELAY 0xfffffffc\n")
for src, dst in NAMES.items():
    m = re.search(r"sensor_2l3_setfile_B_%s\[\]\s*=\s*\{(.*?)\n\};" % src, text, re.S)
    rows = re.findall(r"^\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)", m.group(1), re.M)
    print("static const u32 tb_%s[] = {" % dst)
    for a, v, w in rows:
        a = {"I2C_MODE_BURST_ADDR": "TB_BURST_ADDR", "I2C_MODE_BURST_DATA": "TB_BURST_DATA", "I2C_MODE_DELAY": "TB_DELAY"}.get(a, a)
        print("\t%s, %s, %s," % (a, v, w))
    print("};\n")
