#!/usr/bin/env python3
"""gen-cis-tables.py 2L3-SETB.H 3H1-SETA.H > zrn-cam-tables.h: Samsung's register tables.

The inputs are fimc-is-cis-2l3-setB.h and fimc-is-cis-3h1-setA.h from the vendor kernel. Each row is register, value, width;
the burst and delay rows keep their meaning from sensor_cis_set_registers()."""
import re, sys
print("/* SPDX-License-Identifier: GPL-2.0 */\n/* Generated by gen-cis-tables.py from the vendor kernel's fimc-is-cis-*-set*.h */")
print("#define TB_BURST_ADDR 0xfffffffe\n#define TB_BURST_DATA 0xfffffffd\n#define TB_DELAY 0xfffffffc\n")
SRC = [(sys.argv[1], "sensor_2l3_setfile_B_", {"Reset_TnP": "reset_tnp", "Global": "global", "2016x1512_30fps": "mode_2016x1512_30", "4032x3024_30fps": "mode_4032x3024_30"}),
       (sys.argv[2], "sensor_3h1_setfile_A_", {"1632x1224_30fps": "front_1632x1224_30", "3264x2448_30fps": "front_3264x2448_30"})]
for path, prefix, names in SRC:
    text = open(path, errors="ignore").read()
    for src, dst in names.items():
        m = re.search(r"%s%s\[\]\s*=\s*\{(.*?)\n\};" % (prefix, src), text, re.S)
        rows = re.findall(r"^\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)", m.group(1), re.M)
        print("static const u32 tb_%s[] = {" % dst)
        for a, v, w in rows:
            a = {"I2C_MODE_BURST_ADDR": "TB_BURST_ADDR", "I2C_MODE_BURST_DATA": "TB_BURST_DATA", "I2C_MODE_DELAY": "TB_DELAY"}.get(a, a)
            print("\t%s, %s, %s," % (a, v, w))
        print("};\n")
