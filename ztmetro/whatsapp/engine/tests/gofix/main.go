// The handshake operations of whatsmeow's Noise state with fixed inputs.
func emitNoise() {
	priv := func(b byte) (r [32]byte) {
		for i := range r {
			r[i] = b
		}
		return
	}
	pub := func(p [32]byte) [32]byte {
		kp := ecc.CreateKeyPair(p[:])
		return kp.PublicKey().PublicKey()
	}
	e, se, cs := priv(0x11), priv(0x22), priv(0x33)
	ePub, sePub, csPub := pub(e), pub(se), pub(cs)
	fmt.Println("noise epriv", hx(e[:]))
	fmt.Println("noise sepub", hx(sePub[:]))
	fmt.Println("noise cspriv", hx(cs[:]))
	nh := socket.NewNoiseHandshake()
	nh.Start(socket.NoiseStartPattern, []byte{'W', 'A', 6, 3})
	nh.Authenticate(ePub[:])
	nh.Authenticate(sePub[:])
	if err := nh.MixSharedSecretIntoKey(e, sePub); err != nil {
		panic(err)
	}
	fmt.Println("noise enc1", hx(nh.Encrypt([]byte("first plaintext"))))
	fmt.Println("noise enc2", hx(nh.Encrypt([]byte("second"))))
	if err := nh.MixSharedSecretIntoKey(cs, sePub); err != nil {
		panic(err)
	}
	fmt.Println("noise enc3", hx(nh.Encrypt(csPub[:])))
}

func emitSig() {
	kp := ecc.CreateKeyPair(uh(strings.Repeat("42", 32)))
	msg := []byte("xeddsa interop message")
	sig := ecc.CalculateSignature(kp.PrivateKey(), msg)
	pub := kp.PublicKey().PublicKey()
	fmt.Println("sig pub", hx(pub[:]))
	fmt.Println("sig msg", hx(msg))
	fmt.Println("sig val", hx(sig[:]))
}

// A Go party with in-memory stores, driven over stdin by the C++ interop test.
type peer struct {
	ser     *serialize.Serializer
	id      *identity.KeyPair
	reg     uint32
	ss      *tests.InMemorySession
	pks     *tests.InMemoryPreKey
	spks    *tests.InMemorySignedPreKey
	ids     *tests.InMemoryIdentityKey
	sks     *tests.InMemorySenderKey
	remote  *protocol.SignalAddress
	builder *session.Builder
	cipher  *session.Cipher
}

func key(hexpub string) *ecc.DjbECPublicKey {
	var a [32]byte
	copy(a[:], uh(hexpub))
	return ecc.NewDjbECPublicKey(a)
}

func newPeer() *peer {
	ser := serialize.NewProtoBufSerializer()
	kp, _ := ecc.GenerateKeyPair()
	id := identity.NewKeyPair(identity.NewKey(kp.PublicKey()), kp.PrivateKey())
	p := &peer{ser: ser, id: id, reg: 4242}
	p.ss = tests.NewInMemorySession(ser)
	p.pks = tests.NewInMemoryPreKey()
	p.spks = tests.NewInMemorySignedPreKey()
	p.ids = tests.NewInMemoryIdentityKey(id, p.reg)
	p.sks = tests.NewInMemorySenderKey()
	p.remote = protocol.NewSignalAddress("cpp", 1)
	p.builder = session.NewBuilder(p.ss, p.pks, p.spks, p.ids, p.remote, ser)
	p.cipher = session.NewCipher(p.builder, p.remote)
	return p
}

func (p *peer) myBundle() string {
	pkKP, _ := ecc.GenerateKeyPair()
	spkKP, _ := ecc.GenerateKeyPair()
	pk := record.NewPreKey(77, pkKP, p.ser.PreKeyRecord)
	sigd := spkKP.PublicKey().Serialize()
	sig := ecc.CalculateSignature(p.id.PrivateKey(), sigd)
	spk := record.NewSignedPreKey(88, 0, spkKP, sig, p.ser.SignedPreKeyRecord)
	ctx := context.Background()
	_ = p.pks.StorePreKey(ctx, 77, pk)
	_ = p.spks.StoreSignedPreKey(ctx, 88, spk)
	a, b, c := pkKP.PublicKey().PublicKey(), spkKP.PublicKey().PublicKey(), p.id.PublicKey().PublicKey().PublicKey()
	return fmt.Sprintf("%d 77 %s 88 %s %s %s", p.reg, hx(a[:]), hx(b[:]), hx(sig[:]), hx(c[:]))
}

func (p *peer) serve() {
	ctx := context.Background()
	in := bufio.NewScanner(os.Stdin)
	in.Buffer(make([]byte, 1<<20), 1<<24)
	skn := protocol.NewSenderKeyName("group", protocol.NewSignalAddress("go", 1))
	cppSkn := protocol.NewSenderKeyName("group", protocol.NewSignalAddress("cpp", 1))
	gb := groups.NewGroupSessionBuilder(p.sks, p.ser)
	reply := func(a ...any) { fmt.Println(a...); os.Stdout.Sync() }
	for in.Scan() {
		f := strings.Fields(in.Text())
		if len(f) == 0 {
			continue
		}
		switch f[0] {
		case "bundle":
			reply(p.myBundle())
		case "process": // reg pkid pk spkid spk sig ik
			var reg, pkid, spkid uint32
			fmt.Sscan(f[1], &reg)
			fmt.Sscan(f[2], &pkid)
			fmt.Sscan(f[4], &spkid)
			var sig [64]byte
			copy(sig[:], uh(f[6]))
			b := prekey.NewBundle(reg, 1, optional.NewOptionalUint32(pkid), spkid,
				key(f[3]), key(f[5]), sig, identity.NewKey(key(f[7])))
			if err := p.builder.ProcessBundle(ctx, b); err != nil {
				reply("err", err)
			} else {
				reply("ok")
			}
		case "enc":
			m, err := p.cipher.Encrypt(ctx, uh(f[1]))
			if err != nil {
				reply("err", err)
				continue
			}
			t := "msg"
			if m.Type() == protocol.PREKEY_TYPE {
				t = "pkmsg"
			}
			reply(t, hx(m.Serialize()))
		case "dec":
			var pt []byte
			var err error
			if f[1] == "pkmsg" {
				var m *protocol.PreKeySignalMessage
				m, err = protocol.NewPreKeySignalMessageFromBytes(uh(f[2]), p.ser.PreKeySignalMessage, p.ser.SignalMessage)
				if err == nil {
					pt, err = p.cipher.DecryptMessage(ctx, m)
				}
			} else {
				var m *protocol.SignalMessage
				m, err = protocol.NewSignalMessageFromBytes(uh(f[2]), p.ser.SignalMessage)
				if err == nil {
					pt, err = p.cipher.Decrypt(ctx, m)
				}
			}
			if err != nil {
				reply("err", err)
			} else {
				reply("ok", hx(pt))
			}
		case "skdm":
			m, err := gb.Create(ctx, skn)
			if err != nil {
				reply("err", err)
			} else {
				reply(hx(m.Serialize()))
			}
		case "skenc":
			c := groups.NewGroupCipher(gb, skn, p.sks)
			m, err := c.Encrypt(ctx, uh(f[1]))
			if err != nil {
				reply("err", err)
			} else {
				reply(hx(m.SignedSerialize()))
			}
		case "skproc":
			m, err := protocol.NewSenderKeyDistributionMessageFromBytes(uh(f[1]), p.ser.SenderKeyDistributionMessage)
			if err == nil {
				err = gb.Process(ctx, cppSkn, m)
			}
			if err != nil {
				reply("err", err)
			} else {
				reply("ok")
			}
		case "skdec":
			c := groups.NewGroupCipher(gb, cppSkn, p.sks)
			m, err := protocol.NewSenderKeyMessageFromBytes(uh(f[1]), p.ser.SenderKeyMessage)
			var pt []byte
			if err == nil {
				pt, err = c.Decrypt(ctx, m)
			}
			if err != nil {
				reply("err", err)
			} else {
				reply("ok", hx(pt))
			}
		case "quit":
			return
		}
	}
}

func main() {
	if len(os.Args) < 2 {
		os.Exit(2)
	}
	switch os.Args[1] {
	case "tokens":
		emitTokens()
	case "fixtures":
		emitCodec()
		emitNoise()
		emitSig()
	case "peer":
		newPeer().serve()
	}
}
