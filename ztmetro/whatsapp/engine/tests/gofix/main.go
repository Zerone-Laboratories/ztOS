var _ = groupRecord.NewSenderKey

func hx(b []byte) string { return hex.EncodeToString(b) }
func uh(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return b
}

func emitTokens() {
	q := func(s string) string { return fmt.Sprintf("%q", s) }
	fmt.Println("// Generated by tests/gofix tokens. WhatsApp's fixed wire dictionary (protocol data).")
	fmt.Printf("#define WA_DICT_VERSION %d\n", token.DictVersion)
	fmt.Println("static const char* const kSingle[] = {")
	for _, t := range token.SingleByteTokens {
		fmt.Println(q(t) + ",")
	}
	fmt.Println("};")
	for i, d := range token.DoubleByteTokens {
		fmt.Printf("static const char* const kDouble%d[] = {\n", i)
		for _, t := range d {
			fmt.Println(q(t) + ",")
		}
		fmt.Println("};")
	}
}

// Each line: name, hex of whatsmeow's marshal. Only nodes with at most one attribute,
// because Go map order would make longer ones unstable.
