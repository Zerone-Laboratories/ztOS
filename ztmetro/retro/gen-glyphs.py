#!/usr/bin/env python3
"""Turn ZrnDotMatrix's glyph tables (its web/*.js) into retro/dm-glyphs.h.

    gen-glyphs.py /path/to/ZrnDotMatrix/app/src/main/assets/web > retro/dm-glyphs.h

The tables are data: the digits, the 3x5 font, the status and widget icons,
the dock icons and the ZERONE wordmark, as rows of 'X' (lit), '+' (dim),
'*' (accent) and '.' (off). Run again when the Android app's glyphs change.
"""
import json, re, sys
from pathlib import Path

web = Path(sys.argv[1])
engine = (web / 'engine.js').read_text()
core = (web / 'launcher-core.js').read_text()
icons = (web / 'icons.js').read_text()


def js_object(src, name):
    """The object literal `const NAME = {...};` as Python, for these simple tables."""
    m = re.search(r'const ' + name + r'\s*=\s*\{', src)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{': depth += 1
        elif src[j] == '}':
            depth -= 1
            if not depth:
                body = src[i:j + 1]
                break
    body = re.sub(r'//[^\n]*', '', body)
    body = re.sub(r"(?<=[{,\s])([A-Za-z_][A-Za-z0-9_]*)\s*:", r'"\1":', body)
    body = body.replace("'", '"')
    body = re.sub(r'"\\""', '"\'"', body)
    body = re.sub(r',\s*([}\]])', r'\1', body)
    return json.loads(body)


def js_array(src, name):
    m = re.search(r'const ' + name + r'\s*=\s*\[', src)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '[': depth += 1
        elif src[j] == ']':
            depth -= 1
            if not depth:
                body = src[i:j + 1]
                break
    body = re.sub(r'//[^\n]*', '', body).replace("'", '"')
    body = re.sub(r',\s*([}\]])', r'\1', body)
    return json.loads(body)


def cname(s):
    return re.sub(r'[^A-Za-z0-9]', '_', s)


out = ['/* Generated by gen-glyphs.py from ZrnDotMatrix (github.com/z3r0n3br4instorm/ZrnDotMatrix): do not edit. */',
       '#pragma once', '#include "dotmatrix.h"', '']


def bmp(name, rows):
    w = max(len(r) for r in rows)
    out.append('static const char *const %s_rows[] = { %s };' % (name, ', '.join('"%s"' % r for r in rows)))
    out.append('static const struct dm_bmp %s = { %d, %d, %s_rows };' % (name, w, len(rows), name))


# 7x11 digits, indexed by character
b7 = js_object(engine, 'B7')
for k, rows in b7.items():
    bmp('dm_b7_' + {' ': 'space', '-': 'dash'}.get(k, k), rows)
out.append('static const struct dm_bmp *dm_b7(int ch) {')
out.append('\tswitch (ch) {')
for k in b7:
    out.append("\tcase '%s': return &dm_b7_%s;" % (k, {' ': 'space', '-': 'dash'}.get(k, k)))
out.append('\tdefault: return &dm_b7_space;\n\t}\n}')

# 3x5 font: rows separated by spaces, width 1..3
f3_src = engine[engine.index('const F3'):]
f3_src = f3_src[:f3_src.index('};')]
f3 = {m.group(2): m.group(3) for m in re.finditer(r"""(['"])(.+?)\1\s*:\s*'([^']*)'""", f3_src.split('{', 1)[1])}
out.append('/* the 3x5 font, by byte; 0xb0 is the degree sign (decoded from UTF-8) */')
out.append('static const char *const dm_f3[256] = {')
for k, v in f3.items():
    code = 0xb0 if k == '°' else ord(k)
    esc = k.replace('\\', '\\\\').replace("'", "\\'")
    out.append("\t[%d] = \"%s\",\t/* %s */" % (code, v, '°' if code == 0xb0 else esc))
out.append('};')

for name, rows in js_object(engine, 'ICON').items():
    bmp('dm_icon_' + name, rows)
for i, glyph in enumerate(js_array(engine, 'ZERONE')):
    bmp('dm_zerone_%d' % i, glyph)
out.append('static const struct dm_bmp *const dm_zerone[6] = { %s };' % ', '.join('&dm_zerone_%d' % i for i in range(6)))
for i, glyph in enumerate(js_array(engine, 'ZERONE_MINI')):
    bmp('dm_zerone_mini_%d' % i, glyph)
out.append('static const int dm_ecg[] = { %s };' % ', '.join(str(x) for x in js_array(engine, 'ECG')))

# the launcher's widget bitmaps
for name in ('WIFI_BIG', 'BT_BIG', 'WARN_TRI', 'CHARGE_BOLT', 'LIGHTNING_BOLT', 'MEDIA_PREV', 'MEDIA_PLAY',
             'MEDIA_PAUSE', 'MEDIA_NEXT'):
    bmp('dm_' + name.lower(), js_array(core, name))
out.append('static const int dm_wifi_stages[] = { %s };' % ', '.join(map(str, js_array(core, 'WIFI_STAGES'))))

# dock, status and context icons
ic = json.loads(icons[icons.index('{'):icons.rindex('}') + 1])
for name, rows in ic.items():
    bmp('dm_icons_' + cname(name), rows)
print('\n'.join(out))
